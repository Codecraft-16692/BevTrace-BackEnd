package com.codecraft.bevtrace.platform.iam.infrastructure.persistence.seeding;

import com.codecraft.bevtrace.platform.iam.application.internal.outboundservices.hashing.HashingService;
import com.codecraft.bevtrace.platform.iam.domain.model.aggregates.User;
import com.codecraft.bevtrace.platform.iam.domain.model.entities.Role;
import com.codecraft.bevtrace.platform.iam.domain.repositories.RoleRepository;
import com.codecraft.bevtrace.platform.iam.domain.repositories.UserRepository;
import com.codecraft.bevtrace.platform.iam.domain.services.PasswordPolicy;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

/**
 * Creates, when missing, the three roles of the platform and the administrator account. The administrator is
 * generated by the system (it cannot self-register); every other user goes through the sign-up and waits for a
 * permission. It is idempotent: it never overwrites an existing role or user.
 */
@Component
public class IamDataInitializer implements ApplicationRunner {

    private static final Logger LOG = LoggerFactory.getLogger(IamDataInitializer.class);

    private final RoleRepository roles;
    private final UserRepository users;
    private final HashingService hashing;
    private final String adminName;
    private final String adminEmail;
    private final String adminPassword;

    public IamDataInitializer(RoleRepository roles, UserRepository users, HashingService hashing,
                              @Value("${bevtrace.admin.name:Administrator}") String adminName,
                              @Value("${bevtrace.admin.email:}") String adminEmail,
                              @Value("${bevtrace.admin.password:}") String adminPassword) {
        this.roles = roles;
        this.users = users;
        this.hashing = hashing;
        this.adminName = adminName;
        this.adminEmail = adminEmail;
        this.adminPassword = adminPassword;
    }

    @Override
    @Transactional
    public void run(ApplicationArguments args) {
        var admin = ensureRole(Role.ADMIN, true);
        ensureRole(Role.LOGISTICS_MANAGER, false);
        ensureRole(Role.WAREHOUSE_OPERATOR, false);
        ensureAdminUser(admin);
    }

    private Role ensureRole(String name, boolean isAdmin) {
        return roles.findByName(name).orElseGet(() -> {
            LOG.info("Creating role {}", name);
            return roles.save(Role.create(name, isAdmin));
        });
    }

    private void ensureAdminUser(Role adminRole) {
        if (adminEmail.isBlank() || adminPassword.isBlank()) {
            LOG.warn("bevtrace.admin.email / bevtrace.admin.password are not set: no administrator is created");
            return;
        }
        var email = adminEmail.trim().toLowerCase();
        if (users.existsByEmail(email)) {
            return;
        }
        PasswordPolicy.requireStrong(adminPassword);
        users.save(User.register(adminRole.getId(), adminName, email, hashing.encode(adminPassword), "", true));
        LOG.info("Administrator {} created", email);
    }
}
